/*
 * ir3asm: Mesa's ir3 assembler (the computerator syntax) for the Adreno 530,
 * without a GPU or DRM. Prints the shader info the a5xx compute state needs,
 * the binary as a C array and Mesa's disassembly of it. Built from a Mesa
 * checkout by tools/build-ir3asm.sh.
 *
 *   ir3asm FILE.asm [NAME]   -> C on stdout, disassembly on stderr
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ir3/ir3_assembler.h"
#include "ir3/ir3_compiler.h"
#include "ir3/ir3_shader.h"
#include "ir3-isa.h"

int
main(int argc, char **argv)
{
	if (argc < 2) {
		fprintf(stderr, "usage: %s FILE.asm [NAME]\n", argv[0]);
		return 1;
	}
	const char *name = argc > 2 ? argv[2] : "shader";

	/* freedreno_devices.py, GPUId(530) */
	static struct fd_dev_info info;
	info.chip = 5;
	info.num_sp_cores = 4;
	info.wave_granularity = 2;
	info.fibers_per_sp = 64 * 16;
	info.highest_bank_bit = 15;
	info.threadsize_base = 32;
	info.cs_shared_mem_size = 32 * 1024;
	info.props.reg_size_vec4 = 64;
	static struct fd_dev_id id = {.gpu_id = 530};

	/* ir3_compiler_create(), the gen 5 values */
	static struct ir3_compiler c;
	c.dev_id = &id;
	c.gen = 5;
	c.info = &info;
	c.branchstack_size = 256;
	c.max_branchstack = 64;
	c.max_variable_workgroup_size = 1024;
	c.num_predicates = 1;
	c.delay_slots.alu_to_alu = 3;
	c.delay_slots.non_alu = 6;
	c.delay_slots.cat3_src2_read = 2;
	c.max_const_pipeline = c.max_const_geom = c.max_const_frag = c.max_const_compute = 512;
	c.max_const_safe = 256;
	c.compute_lb_size = 512 * 16 * 2 + 32 * 1024;
	c.pvtmem_per_fiber_align = 512;
	c.has_pvtmem = true;
	c.reg_size_vec4 = 64;
	c.flat_bypass = true;
	c.array_index_add_half = true;
	c.instr_align = 16;
	c.const_upload_unit = 4;
	c.bool_type = TYPE_U16;
	c.has_shared_regfile = true;
	c.has_bitwise_triops = true;
	c.cat3_rel_offset_0_quirk = true;

	FILE *in = fopen(argv[1], "r");
	if (!in) {
		perror(argv[1]);
		return 1;
	}
	struct ir3_kernel_info ki = {0};
	struct ir3_shader *s = ir3_parse_asm(&c, &ki, in);
	if (!s) {
		fprintf(stderr, "assembly failed\n");
		return 1;
	}
	struct ir3_shader_variant *v = s->variants;
	const struct ir3_info *i = &v->info;
	uint32_t *bin = v->bin;
	unsigned ndw = i->size / 4;

	printf("/* %s: generated by tools/ir3asm from %s */\n", name, argv[1]);
	printf("#define %s_INSTRLEN %u    /* units of 16 instructions */\n", name, v->instrlen);
	printf("#define %s_CONSTLEN %u    /* vec4 */\n", name, v->constlen);
	printf("#define %s_MAX_REG %d\n", name, i->max_reg);
	printf("#define %s_MAX_HALF_REG %d\n", name, i->max_half_reg);
	printf("#define %s_DOUBLE_THREADSIZE %d\n", name, i->double_threadsize);
	printf("#define %s_BRANCHSTACK %u\n", name, ir3_shader_branchstack_hw(v));
	printf("#define %s_LOCAL_SIZE %u, %u, %u\n", name, v->local_size[0], v->local_size[1], v->local_size[2]);
	printf("#define %s_LOCALID_REGID 0x%x\n", name, ir3_find_sysval_regid(v, SYSTEM_VALUE_LOCAL_INVOCATION_ID));
	printf("#define %s_WGID_REGID 0x%x\n", name, ir3_find_sysval_regid(v, SYSTEM_VALUE_WORKGROUP_ID));
	printf("#define %s_NUM_BUFS %u\n", name, ki.num_bufs);
	printf("static const uint32_t %s[%u] = {", name, ndw);
	for (unsigned n = 0; n < ndw; n++) {
		printf("%s0x%08x,", n % 8 ? " " : "\n\t", bin[n]);
	}
	printf("\n};\n");

	ir3_isa_disasm(bin, i->size, stderr, &(struct isa_decode_options){
		.show_errors = true,
		.branch_labels = true,
		.gpu_id = 530,
	});
	return 0;
}
